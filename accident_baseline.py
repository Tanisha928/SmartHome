import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

class AudioDataset(Dataset):
    def __init__(self, npz_file):
        data = np.load(npz_file)
        self.spectrograms = data['spectrograms']
        self.labels = data['labels']

    def __len__(self):
        return len(self.spectrograms)

    def __getitem__(self, idx):
        spec = self.spectrograms[idx]
        spec = torch.tensor(spec, dtype=torch.float32).unsqueeze(0)
        label = torch.tensor(self.labels[idx], dtype=torch.long)
        return spec, label

class AudioCRNN(nn.Module):
    def __init__(self, num_classes=3):
        super(AudioCRNN, self).__init__()
        self.conv1 = nn.Conv2d(1, 16, kernel_size=3, stride=1, padding=1)
        self.conv2 = nn.Conv2d(16, 32, kernel_size=3, stride=1, padding=1)
        self.conv3 = nn.Conv2d(32, 64, kernel_size=3, stride=1, padding=1)
        self.pool = nn.MaxPool2d(kernel_size=2, stride=2)
        self.relu = nn.ReLU()
        self.bn1 = nn.BatchNorm2d(16)
        self.bn2 = nn.BatchNorm2d(32)
        self.bn3 = nn.BatchNorm2d(64)
        self.gru = nn.GRU(input_size=64 * 16, hidden_size=128, num_layers=1, batch_first=True)
        self.fc1 = nn.Linear(128, 128)
        self.fc2 = nn.Linear(128, num_classes)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x):
        x = self.pool(self.relu(self.bn1(self.conv1(x))))
        x = self.pool(self.relu(self.bn2(self.conv2(x))))
        x = self.pool(self.relu(self.bn3(self.conv3(x))))
        batch, channels, height, width = x.size()
        x = x.permute(0, 3, 1, 2).contiguous()
        x = x.view(batch, width, channels * height)
        x, _ = self.gru(x)
        x = x[:, -1, :]
        x = self.relu(self.fc1(x))
        x = self.dropout(x)
        x = self.fc2(x)
        return x

import torch.optim as optim
from torchmetrics import Accuracy, Precision, Recall, F1Score
import numpy as np
from sklearn.metrics import roc_curve, auc
import matplotlib.pyplot as plt

def train_model(npz_file, epochs=30, batch_size=32, lr=0.0005, patience=5):
    dataset = AudioDataset(npz_file)
    labels = [label.item() for _, label in dataset]
    class_counts = np.bincount(labels)
    num_samples = len(labels)
    class_weights = torch.tensor([num_samples / (len(class_counts) * count) for count in class_counts], dtype=torch.float32)
    if torch.cuda.is_available():
        class_weights = class_weights.cuda()

    train_accuracy = Accuracy(task="multiclass", num_classes=3).cuda() if torch.cuda.is_available() else Accuracy(task="multiclass", num_classes=3)
    train_precision = Precision(task="multiclass", num_classes=3, average='macro').cuda() if torch.cuda.is_available() else Precision(task="multiclass", num_classes=3, average='macro')
    train_recall = Recall(task="multiclass", num_classes=3, average='macro').cuda() if torch.cuda.is_available() else Recall(task="multiclass", num_classes=3, average='macro')
    train_f1 = F1Score(task="multiclass", num_classes=3, average='macro').cuda() if torch.cuda.is_available() else F1Score(task="multiclass", num_classes=3, average='macro')

    train_size = int(0.8 * len(dataset))
    val_size = len(dataset) - train_size
    train_dataset, val_dataset = torch.utils.data.random_split(dataset, [train_size, val_size])
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)

    model = AudioCRNN(num_classes=3)
    if torch.cuda.is_available():
        model = model.cuda()
    criterion = nn.CrossEntropyLoss(weight=class_weights)
    optimizer = optim.Adam(model.parameters(), lr=lr)

    best_val_loss = float('inf')
    patience_counter = 0
    train_acc_history = []
    train_prec_history = []
    train_rec_history = []
    train_f1_history = []

    all_val_preds = []
    all_val_labels = []
    all_val_probs = []

    for epoch in range(epochs):
        model.train()
        running_loss = 0.0
        train_preds = []
        train_labels = []

        for specs, labels in train_loader:
            if torch.cuda.is_available():
                specs, labels = specs.cuda(), labels.cuda()
            optimizer.zero_grad()
            outputs = model(specs)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()

            _, predicted = torch.max(outputs, 1)
            train_preds.extend(predicted.cpu().numpy())
            train_labels.extend(labels.cpu().numpy())

        train_acc = train_accuracy(torch.tensor(train_preds), torch.tensor(train_labels))
        train_prec = train_precision(torch.tensor(train_preds), torch.tensor(train_labels))
        train_rec = train_recall(torch.tensor(train_preds), torch.tensor(train_labels))
        train_f1_score = train_f1(torch.tensor(train_preds), torch.tensor(train_labels))

        train_acc_history.append(train_acc.item())
        train_prec_history.append(train_prec.item())
        train_rec_history.append(train_rec.item())
        train_f1_history.append(train_f1_score.item())

        model.eval()
        val_loss = 0.0
        val_preds = []
        val_labels = []
        val_probs = []
        correct = 0
        total = 0
        with torch.no_grad():
            for specs, labels in val_loader:
                if torch.cuda.is_available():
                    specs, labels = specs.cuda(), labels.cuda()
                outputs = model(specs)
                val_loss += criterion(outputs, labels).item()
                probs = torch.softmax(outputs, dim=1)
                _, predicted = torch.max(outputs, 1)
                val_probs.extend(probs.cpu().numpy())
                val_preds.extend(predicted.cpu().numpy())
                val_labels.extend(labels.cpu().numpy())
                total += labels.size(0)
                correct += (predicted == labels).sum().item()

        val_acc = 100 * correct / total
        val_loss = val_loss / len(val_loader)
        print(f"Epoch {epoch+1}/{epochs}, "
              f"Train Loss: {running_loss/len(train_loader):.4f}, "
              f"Train Acc: {train_acc:.4f}, Train Prec: {train_prec:.4f}, "
              f"Train Rec: {train_rec:.4f}, Train F1: {train_f1_score:.4f}, "
              f"Val Loss: {val_loss:.4f}, Val Acc: {val_acc:.2f}%")

        all_val_preds.extend(val_preds)
        all_val_labels.extend(val_labels)
        all_val_probs.extend(val_probs)

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0
            torch.save(model.state_dict(), "multi_audio_crnn.pth")
            print("Model saved (improved validation loss)")
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print(f"Early stopping triggered after {patience} epochs without improvement")
                break

    avg_train_acc = np.mean(train_acc_history)
    avg_train_prec = np.mean(train_prec_history)
    avg_train_rec = np.mean(train_rec_history)
    avg_train_f1 = np.mean(train_f1_history)
    print(f"\nAverage Training Metrics: Acc: {avg_train_acc:.4f}, Prec: {avg_train_prec:.4f}, "
          f"Rec: {avg_train_rec:.4f}, F1: {avg_train_f1:.4f}")

    val_labels_onehot = np.eye(3)[all_val_labels]
    fpr = dict()
    tpr = dict()
    roc_auc = dict()
    for i in range(3):
        fpr[i], tpr[i], _ = roc_curve(val_labels_onehot[:, i], [prob[i] for prob in all_val_probs])
        roc_auc[i] = auc(fpr[i], tpr[i])
    plt.figure()
    for i in range(3):
        plt.plot(fpr[i], tpr[i], label=f'Class {i} (AUC = {roc_auc[i]:.2f})')
    plt.plot([0, 1], [0, 1], 'k--')
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title('Average Validation ROC Curve')
    plt.legend(loc="lower right")
    plt.show()

    val_accuracy = Accuracy(task="multiclass", num_classes=3)(torch.tensor(all_val_preds), torch.tensor(all_val_labels))
    val_precision = Precision(task="multiclass", num_classes=3, average='macro')(torch.tensor(all_val_preds), torch.tensor(all_val_labels))
    val_recall = Recall(task="multiclass", num_classes=3, average='macro')(torch.tensor(all_val_preds), torch.tensor(all_val_labels))
    val_f1 = F1Score(task="multiclass", num_classes=3, average='macro')(torch.tensor(all_val_preds), torch.tensor(all_val_labels))
    print(f"Average Validation - Acc: {val_accuracy:.4f}, Prec: {val_precision:.4f}, Rec: {val_recall:.4f}, F1: {val_f1:.4f}")

    print("Model saved to multi_audio_crnn.pth")

train_model('multi_audio_dataset.npz')

import os
