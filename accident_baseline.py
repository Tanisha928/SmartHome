import matplotlib.pyplot as plt
from torchmetrics import Accuracy, Precision, Recall, F1Score

def predict_audio(model_path, audio_path, class_map={0: 'glass break', 1: 'traffic', 2: 'car crash'}, confidence_threshold=0.9):
    model = AudioCRNN(num_classes=3)
    if not os.path.exists(model_path):
        print(f"Error: Model file {model_path} not found")
        return None
    model.load_state_dict(torch.load(model_path, map_location=torch.device('cpu')))
    model.eval()

    if not os.path.exists(audio_path):
        print(f"Error: Audio file {audio_path} not found")
        return None
    try:
        from . import audio_to_melspec
        spec = audio_to_melspec(audio_path)
        if spec is None or np.all(np.isnan(spec)):
            print(f"Error: Invalid spectrogram for {audio_path}")
            return None
        spec = torch.tensor(spec, dtype=torch.float32).unsqueeze(0).unsqueeze(0)
        output = model(spec)
        probabilities = torch.softmax(output, dim=1).detach().numpy()[0]
        max_prob = np.max(probabilities)
        _, predicted = torch.max(output, 1)
        class_probs = dict(zip(class_map.values(), probabilities))
        print(f"Class probabilities: {class_probs}")
        if max_prob < confidence_threshold:
            print(f"Warning: Low confidence (max probability {max_prob:.4f} < {confidence_threshold}), prediction may be unreliable")
            return "Uncertain"
        print(f"Predicted class: {class_map[predicted.item()]}")
        return class_map[predicted.item()]
    except Exception as e:
        print(f"Error during inference: {e}")
        return None

