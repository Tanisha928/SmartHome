# Augmentation pipeline
augment = Compose([
    AddGaussianNoise(min_amplitude=0.001, max_amplitude=0.01, p=0.5),
    TimeStretch(min_rate=0.8, max_rate=1.2, p=0.5),
    PitchShift(min_semitones=-2, max_semitones=2, p=0.5),
    Shift(min_shift=-0.2, max_shift=0.2, p=0.5),
])

def augment_and_save(input_path, output_dir, num_augmentations=3, sr=16000):
    os.makedirs(output_dir, exist_ok=True)
    audio, _ = librosa.load(input_path, sr=sr)  # Load any format
    filename = os.path.basename(input_path).rsplit('.', 1)[0] + '.wav'
    sf.write(os.path.join(output_dir, f"original_{filename}"), audio, sr)
    for i in range(num_augmentations):
        augmented_audio = augment(samples=audio, sample_rate=sr)
        output_path = os.path.join(output_dir, f"aug_{i}_{filename}")
        sf.write(output_path, augmented_audio, sr)
        print(f"Saved: {output_path}")

def augment_dataset(input_dir, output_dir, num_augmentations=3):
    for filename in os.listdir(input_dir):
        input_path = os.path.join(input_dir, filename)
        if os.path.isfile(input_path):
            augment_and_save(input_path, output_dir, num_augmentations)

