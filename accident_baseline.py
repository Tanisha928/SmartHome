import numpy as np

def audio_to_melspec(audio_path, sr=16000, n_mels=128, n_fft=2048, hop_length=512, fixed_length=128):
    """
    Convert audio to Mel spectrogram with safe normalization.
    """
    try:
        audio, _ = librosa.load(audio_path, sr=sr, duration=2.0)
        if len(audio) == 0:
            print(f"Warning: Empty audio file skipped: {audio_path}")
            return np.zeros((n_mels, fixed_length))
    except Exception as e:
        print(f"Error loading {audio_path}: {e}")
        return np.zeros((n_mels, fixed_length))

    mel_spec = librosa.feature.melspectrogram(y=audio, sr=sr, n_mels=n_mels, n_fft=n_fft, hop_length=hop_length)
    mel_spec_db = librosa.power_to_db(mel_spec, ref=np.max, top_db=None)

    if mel_spec_db.shape[1] > fixed_length:
        mel_spec_db = mel_spec_db[:, :fixed_length]
    else:
        mel_spec_db = np.pad(mel_spec_db, ((0, 0), (0, fixed_length - mel_spec_db.shape[1])), mode='constant')

    min_val = np.min(mel_spec_db)
    max_val = np.max(mel_spec_db)
    range_val = max_val - min_val
    if range_val == 0 or np.isnan(range_val):
        print(f"Warning: No variation in spectrogram for {audio_path}, using zero-normalized output")
        mel_spec_db = np.zeros_like(mel_spec_db)
    else:
        mel_spec_db = (mel_spec_db - min_val) / range_val
    return mel_spec_db

def prepare_dataset(class_dirs, class_labels, output_file='multi_audio_dataset.npz'):
    spectrograms = []
    labels = []
    for dir_path, label in zip(class_dirs, class_labels):
        for filename in os.listdir(dir_path):
            if filename.endswith(".wav"):
                spec = audio_to_melspec(os.path.join(dir_path, filename))
                if spec is not None and not np.all(np.isnan(spec)):
                    spectrograms.append(spec)
                    labels.append(label)
                    print(f"Processed: {filename}")
                else:
                    print(f"Skipped invalid file: {filename}")
    spectrograms = np.array(spectrograms)
    labels = np.array(labels)
    np.savez(output_file, spectrograms=spectrograms, labels=labels)

